package Arrays;

public class Pattern {

	public static void main(String[] args) {
		for(int i=1;i<6;i++) {
			for(int j=1;j<=8;j++) {
				System.out.print ("*");
			}
			System.out.println();
		}

	
	for(int i=2;i>=0;i--) {
		for(int j=3;j>1;j--) {
			System.out.print("*");
		}
		System.out.println();
	}
	}

}
